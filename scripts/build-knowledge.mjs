import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadArticles } from './knowledge-lib.mjs'

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'knowledge.generated.js')
const articles = loadArticles()

const source = `/* Generated by scripts/build-knowledge.mjs. Do not edit. */
export const knowledgeArticles = ${JSON.stringify(articles, null, 2)}

export function articlePath(article) {
  const raw = article?.path || \`/knowledge/\${article?.slug || ''}\`
  if (raw === '/') return raw
  return raw.endsWith('/') ? raw : \`\${raw}/\`
}

export function listArticles(locale) {
  const lang = locale === 'en' ? 'en' : 'ar'
  return knowledgeArticles.map((article) => ({
    slug: article.slug,
    path: article.path,
    featured: article.featured,
    video: article.video,
    poster: article.poster,
    download: article.download,
    title: article[lang].title,
    description: article[lang].description,
    cover: article[lang].cover,
    category: article[lang].category,
    topic: article[lang].topic,
    published: article[lang].published
  }))
}

export function getArticle(slug, locale) {
  const lang = locale === 'en' ? 'en' : 'ar'
  const article = knowledgeArticles.find((item) => item.slug === slug)
  if (!article) return null
  return {
    slug: article.slug,
    path: article.path,
    featured: article.featured,
    video: article.video,
    poster: article.poster,
    download: article.download,
    title: article[lang].title,
    description: article[lang].description,
    cover: article[lang].cover,
    category: article[lang].category,
    topic: article[lang].topic,
    published: article[lang].published,
    updated: article[lang].updated,
    html: article[lang].html
  }
}
`

writeFileSync(out, source)
console.log(`Wrote ${articles.length} knowledge articles`)
